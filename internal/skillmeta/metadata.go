// Package skillmeta reads the canonical single-line skill metadata shared by the catalog and wrappers.
package skillmeta

import (
	"encoding/json"
	"errors"
	"fmt"
	"regexp"
	"slices"
	"strconv"
	"strings"
	"unicode"
	"unicode/utf8"
)

var validName = regexp.MustCompile(`^[a-z0-9-]+$`)

// Scalar accepts the repository's single-line string metadata, including JSON-style
// double quotes and YAML single quotes. It refuses other YAML forms rather than guessing.
func Scalar(raw string) (string, error) {
	raw = strings.TrimSpace(raw)
	if raw == "" {
		return "", errors.New("empty string")
	}
	value := raw
	switch raw[0] {
	case '"':
		if err := json.Unmarshal([]byte(raw), &value); err != nil {
			return "", errors.New("invalid double-quoted string (use JSON escaping)")
		}
	case '\'':
		if len(raw) < 2 || raw[len(raw)-1] != '\'' {
			return "", errors.New("unterminated single-quoted string")
		}
		inner := raw[1 : len(raw)-1]
		value = strings.ReplaceAll(inner, "''", "'")
		for i := 0; i < len(inner); i++ {
			if inner[i] == '\'' {
				if i+1 >= len(inner) || inner[i+1] != '\'' {
					return "", errors.New("unescaped single quote")
				}
				i++
			}
		}
	default:
		if strings.ContainsAny(raw[:1], "[]{}&*!|>@%`#,") || strings.HasPrefix(raw, "- ") || strings.HasPrefix(raw, "? ") || strings.HasPrefix(raw, ": ") || strings.Contains(raw, ": ") || strings.Contains(raw, " #") {
			return "", errors.New("quote YAML punctuation in metadata")
		}
		if slices.Contains([]string{"true", "false", "null", "~", "True", "False", "Null", "TRUE", "FALSE", "NULL"}, raw) {
			return "", errors.New("metadata must be a string")
		}
		if _, err := strconv.ParseFloat(raw, 64); err == nil {
			return "", errors.New("metadata must be a string")
		}
	}
	if value == "" || !utf8.ValidString(value) || strings.ContainsFunc(value, unicode.IsControl) {
		return "", errors.New("metadata must be a nonempty single-line string")
	}
	return value, nil
}

func Metadata(data []byte, directory string) (string, string, error) {
	text := strings.ReplaceAll(string(data), "\r\n", "\n")
	lines := strings.Split(text, "\n")
	if len(lines) < 4 || lines[0] != "---" {
		return "", "", errors.New("missing YAML frontmatter")
	}
	values := map[string]string{}
	closed := false
	for _, line := range lines[1:] {
		if line == "---" {
			closed = true
			break
		}
		key, raw, ok := strings.Cut(line, ":")
		if !ok || (key != "name" && key != "description") {
			return "", "", errors.New("frontmatter permits only name and description")
		}
		if _, ok := values[key]; ok {
			return "", "", fmt.Errorf("duplicate %s", key)
		}
		value, err := Scalar(raw)
		if err != nil {
			return "", "", fmt.Errorf("%s: %w", key, err)
		}
		values[key] = value
	}
	name, desc := values["name"], values["description"]
	if !closed || len(values) != 2 {
		return "", "", errors.New("frontmatter requires name and description and a closing ---")
	}
	if len(name) > 64 || !validName.MatchString(name) || name != directory {
		return "", "", errors.New("name must match its directory and [a-z0-9-]+ within 64 bytes")
	}
	return name, desc, nil
}

// CommandMarker identifies wrappers owned by the canonical-source generator.
const CommandMarker = "<!-- Generated by go run ./scripts/skill-commands; edit agents/skills instead. -->"

// CommandTemplate loads the canonical skill; it never copies its instructions.
func CommandTemplate(name string) string {
	return "Load the `" + name + "` skill with the skill tool and follow it exactly. $ARGUMENTS\n"
}

// CommandWrapper derives the same bytes for repository and catalog descriptors.
func CommandWrapper(name, description string) []byte {
	quoted, _ := json.Marshal(description)
	return []byte("---\ndescription: " + string(quoted) + "\n---\n" + CommandMarker + "\n" + CommandTemplate(name))
}
